// Language management
const LanguageManager = {
    currentLang: 'pl', // Default to Polish
    
    init() {
        // Get saved language or default to Polish
        this.currentLang = localStorage.getItem('language') || 'pl';
        this.applyLanguage();
    },
    
    setLanguage(lang) {
        if (translations[lang]) {
            this.currentLang = lang;
            localStorage.setItem('language', lang);
            this.applyLanguage();
        }
    },
    
    get(key) {
        const keys = key.split('.');
        let value = translations[this.currentLang];
        for (const k of keys) {
            value = value?.[k];
        }
        return value || key;
    },
    
    applyLanguage() {
        // Update navigation
        document.querySelectorAll('[data-translate-nav]').forEach(el => {
            const key = el.getAttribute('data-translate-nav');
            el.textContent = this.get(`nav.${key}`);
        });
        
        // Update hero section
        const heroSubtitle = document.querySelector('.hero-subtitle');
        const heroDesc = document.querySelector('.hero-description');
        if (heroSubtitle) heroSubtitle.textContent = this.get('hero.subtitle');
        if (heroDesc) heroDesc.textContent = this.get('hero.description');
        
        // Update quick links
        document.querySelectorAll('[data-translate-quick]').forEach(el => {
            const key = el.getAttribute('data-translate-quick');
            const parts = key.split('.');
            if (parts[0] === 'title') {
                el.textContent = this.get(`quickLinks.${parts[1]}`);
            } else if (parts[0] === 'desc') {
                el.textContent = this.get(`quickLinks.${parts[1]}Desc`);
            }
        });
        
        // Update page headers
        const pageTitle = document.querySelector('.page-header h1');
        const pageSubtitle = document.querySelector('.page-header .page-subtitle');
        if (pageTitle && pageTitle.getAttribute('data-translate')) {
            const key = pageTitle.getAttribute('data-translate');
            pageTitle.textContent = this.get(key);
        }
        if (pageSubtitle && pageSubtitle.getAttribute('data-translate')) {
            const key = pageSubtitle.getAttribute('data-translate');
            pageSubtitle.textContent = this.get(key);
        }
        
        // Update section titles and content (including paragraphs)
        document.querySelectorAll('[data-translate]').forEach(el => {
            const key = el.getAttribute('data-translate');
            // Skip nav and quickLinks as they're handled separately above
            if (key && !key.startsWith('nav.') && !key.startsWith('quickLinks.')) {
                const value = this.get(key);
                if (value && value !== key) {
                    el.textContent = value;
                }
            }
        });
        
        // Update model hints
        const modelHint = document.querySelector('.model-hints p');
        if (modelHint) modelHint.textContent = this.get('model.dragHint');
        
        const resetBtn = document.getElementById('resetView');
        if (resetBtn) resetBtn.textContent = this.get('model.reset');
        
        // Update loading text
        const loadingText = document.querySelector('#loadingSpinner p');
        if (loadingText) loadingText.textContent = this.get('model.loading');
        
        // Update footer - handled by data-translate attributes
        // Footer elements with data-translate will be updated automatically
        
        // Trigger custom event for other scripts
        document.dispatchEvent(new CustomEvent('languageChanged', { detail: { lang: this.currentLang } }));
    }
};

// Initialize on load
if (document.readyState === 'loading') {
    document.addEventListener('DOMContentLoaded', () => LanguageManager.init());
} else {
    LanguageManager.init();
}
